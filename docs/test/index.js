t.test('autoGenerateMissingDocs', async t => {
  const { autoGenerateMissingDocs } = require('../lib/build.js')
  
  t.test('generates docs for missing commands', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {
        'npm-access.md': createCommandDoc('npm-access', 'Set access level on published packages'),
      },
      navEntries: [
        { title: 'npm access', url: '/commands/npm-access', description: 'Set access level on published packages' },
      ],
      commandFiles: {
        'access.js': `
class AccessCommand {
  static description = 'Set access level on published packages'
}
module.exports = AccessCommand
`,
        'testcmd.js': `
class TestCommand {
  static description = 'A test command'
}
module.exports = TestCommand
`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Verify the doc was created
    const testcmdDocPath = join(contentPath, 'commands', 'npm-testcmd.md')
    const docExists = await fs.access(testcmdDocPath).then(() => true).catch(() => false)
    t.ok(docExists, 'creates documentation file for missing command')
    
    // Verify the doc has correct content
    const docContent = await fs.readFile(testcmdDocPath, 'utf-8')
    t.match(docContent, /title: npm-testcmd/, 'doc has correct title')
    t.match(docContent, /description: A test command/, 'doc has correct description')
    t.match(docContent, /<!-- AUTOGENERATED USAGE DESCRIPTIONS -->/, 'doc has usage placeholder')
    t.match(docContent, /<!-- AUTOGENERATED CONFIG DESCRIPTIONS -->/, 'doc has config placeholder')
    t.match(docContent, /A test command/, 'doc has description in body')
  })

  t.test('updates nav.yml for new commands', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {
        'npm-existing.md': `---
title: npm-existing
section: 1
description: Existing command
---`,
      },
      navEntries: [
        { title: 'npm existing', url: '/commands/npm-existing', description: 'Existing command' },
      ],
      commandFiles: {
        'existing.js': `
class ExistingCommand {
  static description = 'Existing command'
}
module.exports = ExistingCommand
`,
        'newcmd.js': `
class NewCommand {
  static description = 'New command'
}
module.exports = NewCommand
`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Read and verify nav.yml was updated
    const { commandsSection } = await verifyNavStructure(navPath)
    
    t.ok(commandsSection, 'nav has CLI Commands section')
    const newCmdEntry = commandsSection.children.find(c => c.url === '/commands/npm-newcmd')
    t.ok(newCmdEntry, 'nav has entry for new command')
    t.equal(newCmdEntry.title, 'npm newcmd', 'nav entry has correct title')
    t.equal(newCmdEntry.description, 'New command', 'nav entry has correct description')
  })

  t.test('sorts nav children alphabetically', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {},
      navEntries: [
        { title: 'npm zebra', url: '/commands/npm-zebra', description: 'Zebra command' },
        { title: 'npm alpha', url: '/commands/npm-alpha', description: 'Alpha command' },
      ],
      commandFiles: {
        'zebra.js': `module.exports = { description: 'Zebra command' }`,
        'alpha.js': `module.exports = { description: 'Alpha command' }`,
        'beta.js': `module.exports = { description: 'Beta command' }`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Verify sorting
    const { commandsSection } = await verifyNavStructure(navPath)
    
    const titles = commandsSection.children.map(c => c.title)
    
    // npm should be first
    t.equal(titles[0], 'npm', 'npm command is first')
    
    // Rest should be alphabetically sorted
    const rest = titles.slice(1)
    const sorted = [...rest].sort()
    t.same(rest, sorted, 'remaining commands are alphabetically sorted')
    t.ok(titles.includes('npm alpha'), 'includes alpha')
    t.ok(titles.includes('npm beta'), 'includes beta')
    t.ok(titles.includes('npm zebra'), 'includes zebra')
  })

  t.test('handles commands without description', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {},
      navEntries: [],
      commandFiles: {
        'nodesc.js': `module.exports = {}`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Verify fallback description
    const docPath = join(contentPath, 'commands', 'npm-nodesc.md')
    const docContent = await fs.readFile(docPath, 'utf-8')
    t.match(docContent, /description: The nodesc command/, 'uses fallback description in frontmatter')
    t.match(docContent, /The nodesc command/, 'uses fallback description in body')
  })

  t.test('does not add duplicate entries to nav', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {},
      navEntries: [
        { title: 'npm duplicate', url: '/commands/npm-duplicate', description: 'Already exists' },
      ],
      commandFiles: {
        'duplicate.js': `module.exports = { description: 'Already exists' }`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Verify no duplicate
    const { commandsSection } = await verifyNavStructure(navPath)
    
    const duplicateEntries = commandsSection.children.filter(c => c.url === '/commands/npm-duplicate')
    t.equal(duplicateEntries.length, 1, 'does not create duplicate nav entries')
  })

  t.test('skips update when no missing docs', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {
        'npm-complete.md': `---
title: npm-complete
section: 1
description: Complete command
---`,
      },
      navEntries: [
        { title: 'npm complete', url: '/commands/npm-complete', description: 'Complete command' },
      ],
      commandFiles: {
        'complete.js': `module.exports = { description: 'Complete command' }`,
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    const navBefore = await fs.readFile(navPath, 'utf-8')
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    const navAfter = await fs.readFile(navPath, 'utf-8')
    
    t.equal(navBefore, navAfter, 'does not modify nav when no missing docs')
  })

  t.test('handles nav without CLI Commands section', async t => {
    const testDir = t.testdir({
      content: {
        commands: {},
      },
      'nav.yml': `
- title: Other Section
  children: []
`,
      lib: {
        commands: {
          'test.js': `module.exports = { description: 'Test command' }`,
        },
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    // Should not throw, just skip nav update
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Doc should still be created
    const docPath = join(contentPath, 'commands', 'npm-test.md')
    const docExists = await fs.access(docPath).then(() => true).catch(() => false)
    t.ok(docExists, 'creates doc even when nav section missing')
  })

  t.test('handles nav with CLI Commands but no children', async t => {
    const testDir = t.testdir({
      content: {
        commands: {},
      },
      'nav.yml': `
- title: CLI Commands
`,
      lib: {
        commands: {
          'test.js': `module.exports = { description: 'Test command' }`,
        },
      },
    })

    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    // Should not throw, just skip nav children update
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Doc should still be created
    const docPath = join(contentPath, 'commands', 'npm-test.md')
    const docExists = await fs.access(docPath).then(() => true).catch(() => false)
    t.ok(docExists, 'creates doc even when children missing')
  })

  t.test('handles npm command not in first position', async t => {
    const testDir = createAutoGenTestDir(t, {
      existingDocs: {},
      navEntries: [
        { title: 'npm alpha', url: '/commands/npm-alpha', description: 'Alpha command' },
      ],
      commandFiles: {
        'alpha.js': `module.exports = { description: 'Alpha command' }`,
        'beta.js': `module.exports = { description: 'Beta command' }`,
      },
    })

    // Manually adjust nav to put npm not first
    const navPath = join(testDir, 'nav.yml')
    await fs.writeFile(navPath, `
- title: CLI Commands
  children:
    - title: npm alpha
      url: /commands/npm-alpha
    - title: npm
      url: /commands/npm
`)

    const contentPath = join(testDir, 'content')
    const commandsPath = join(testDir, 'lib', 'commands')
    
    await autoGenerateMissingDocs(contentPath, navPath, commandsPath)
    
    // Verify npm moved to first position
    const { commandsSection } = await verifyNavStructure(navPath)
    
    const titles = commandsSection.children.map(c => c.title)
    t.equal(titles[0], 'npm', 'npm command moved to first position')
  })

  t.test('calls autoGenerateMissingDocs via run with default skipAutoGenerate', async t => {
    // This test ensures the default parameter path is covered
    const build = require('../lib/build.js')
    const testDir = t.testdir({
      content: {
        commands: {
          'npm-test.md': createCommandDoc('npm-test', 'Test'),
        },
      },
      'nav.yml': `
- title: CLI Commands
  url: /commands/npm-test
`,
      lib: {
        commands: {
          'test.js': `module.exports = { description: 'Test' }`,
        },
      },
    })

    const template = '<html>{{ content }}</html>'
    await fs.writeFile(join(testDir, 'template.html'), template)
    
    const contentPath = join(testDir, 'content')
    const navPath = join(testDir, 'nav.yml')
    const templatePath = join(testDir, 'template.html')
    const manPath = join(testDir, 'man')
    const htmlPath = join(testDir, 'html')
    const mdPath = join(testDir, 'md')
    
    // Call run with skipAutoGenerate set to true to avoid hitting real commands
    const results = await build({
      content: contentPath,
      template: templatePath,
      nav: navPath,
      man: manPath,
      html: htmlPath,
      md: mdPath,
      skipAutoGenerate: true,
    })
    
    t.ok(results.length > 0, 'build runs successfully')
  })
})

