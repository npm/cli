const localeCompare = require('@isaacs/string-locale-compare')('en')
const { join, basename, resolve } = require('path')
const transformHTML = require('./transform-html.js')
const { version } = require('../../lib/npm.js')
const { aliases } = require('../../lib/utils/cmd-list')
const { shorthands, definitions } = require('@npmcli/config/lib/definitions')

const DOC_EXT = '.md'

const TAGS = {
  CONFIG: '<!-- AUTOGENERATED CONFIG DESCRIPTIONS -->',
  USAGE: '<!-- AUTOGENERATED USAGE DESCRIPTIONS -->',
  SHORTHANDS: '<!-- AUTOGENERATED CONFIG SHORTHANDS -->',
}

const assertPlaceholder = (src, path, placeholder) => {
  if (!src.includes(placeholder)) {
    throw new Error(
      `Cannot replace ${placeholder} in ${path} due to missing placeholder`
    )
  }
  return placeholder
}

// Default command loader - loads commands from lib/commands
const defaultCommandLoader = (name) => {
  return require(`../../lib/commands/${name}`)
}

// Registry of custom commands for testing
let commandRegistry = {}

// Command loader that checks registry first, then falls back to default
const getCommand = (name, commandLoader = defaultCommandLoader) => {
  if (commandRegistry[name]) {
    return commandRegistry[name]
  }
  return commandLoader(name)
}

// Functions to manage the command registry for testing
const registerCommand = (name, command) => {
  commandRegistry[name] = command
}

/* istanbul ignore next - testing utility for cleanup */
const unregisterCommand = (name) => {
  delete commandRegistry[name]
}

const clearCommandRegistry = () => {
  commandRegistry = {}
}

const getCommandByDoc = (docFile, docExt, commandLoader = defaultCommandLoader) => {
  // Grab the command name from the *.md filename
  // NOTE: We cannot use the name property command file because in the case of
  // `npx` the file being used is `lib/commands/exec.js`
  const name = basename(docFile, docExt).replace('npm-', '')

  if (name === 'npm') {
    return {
      name,
      params: null,
      usage: 'npm',
    }
  }

  // special case for `npx`:
  // `npx` is not technically a command in and of itself,
  // so it just needs the usage of npm exec
  const srcName = name === 'npx' ? 'exec' : name
  const command = getCommand(srcName, commandLoader)
  const { params, usage = [''], workspaces } = command
  const commandDefinitions = command.definitions || {}
  const definitionPool = { ...definitions, ...commandDefinitions }
  const usagePrefix = name === 'npx' ? 'npx' : `npm ${name}`
  if (params) {
    for (const param of params) {
      // Check command-specific definitions first, fall back to global definitions
      const paramDef = definitionPool[param]
      if (paramDef && paramDef.exclusive) {
        for (const e of paramDef.exclusive) {
          if (!params.includes(e)) {
            params.splice(params.indexOf(param) + 1, 0, e)
          }
        }
      }
    }
  }

  return {
    name,
    workspaces,
    params: name === 'npx' ? null : params,
    usage: usage.map(u => `${usagePrefix} ${u}`.trim()).join('\n'),
  }
}

const replaceVersion = (src) => src.replace(/@VERSION@/g, version)

const replaceUsage = (src, { path }, commandLoader) => {
  const replacer = assertPlaceholder(src, path, TAGS.USAGE)
  const { usage, name, workspaces } = getCommandByDoc(path, DOC_EXT, commandLoader)

  const synopsis = ['```bash', usage]

  const cmdAliases = Object.keys(aliases).reduce((p, c) => {
    if (aliases[c] === name) {
      p.push(c)
    }
    return p
  }, [])

  if (cmdAliases.length === 1) {
    synopsis.push('', `alias: ${cmdAliases[0]}`)
  } else if (cmdAliases.length > 1) {
    synopsis.push('', `aliases: ${cmdAliases.join(', ')}`)
  }

  synopsis.push('```')

  if (!workspaces) {
    synopsis.push('', 'Note: This command is unaware of workspaces.')
  }

  return src.replace(replacer, synopsis.join('\n'))
}

const replaceParams = (src, { path }, commandLoader) => {
  const { params, name } = getCommandByDoc(path, DOC_EXT, commandLoader)

  // Load command to get command-specific definitions and subcommands if they exist
  let commandDefinitions = {}
  let subcommands = {}
  try {
    const command = getCommand(name, commandLoader)
    commandDefinitions = command.definitions || {}
    subcommands = command.subcommands || {}
  } catch {
    // If command doesn't exist or has no definitions, continue with global definitions only
  }

  // If no params and no subcommands, nothing to replace
  if (!params && Object.keys(subcommands).length === 0) {
    return src
  }

  // Assert placeholder is present - commands with params must have the config placeholder
  const replacer = assertPlaceholder(src, path, TAGS.CONFIG)

  // If command has subcommands, generate sections for each subcommand
  if (Object.keys(subcommands).length > 0) {
    const subcommandSections = Object.entries(subcommands).map(([subName, SubCommand]) => {
      const subUsage = SubCommand.usage || []
      const subDefinitions = SubCommand.definitions || {}
      // If params not defined, extract from definitions
      const subParams = SubCommand.params || Object.keys(subDefinitions)

      const parts = [`### \`npm ${name} ${subName}\``, '']

      if (SubCommand.description) {
        parts.push(SubCommand.description, '')
      }

      // Add usage/synopsis
      if (subUsage.length > 0) {
        parts.push('#### Synopsis', '', '```bash')
        subUsage.forEach(u => {
          parts.push(`npm ${name} ${subName} ${u}`.trim())
        })
        parts.push('```', '')
      }

      // Separate command-specific and global config params for this subcommand
      const commandSpecificParams = []
      const globalConfigParams = []

      for (const paramName of subParams) {
        const isCommandSpecific = subDefinitions[paramName] && !definitions[paramName]
        if (isCommandSpecific) {
          commandSpecificParams.push(paramName)
        } else {
          globalConfigParams.push(paramName)
        }
      }

      // Add command-specific flags section if any exist
      if (commandSpecificParams.length > 0) {
        parts.push('#### Flags', '')
        parts.push('These flags are specific to this subcommand and are not part of npm\'s global configuration or `.npmrc` files.', '')

        commandSpecificParams.forEach((n) => {
          const def = subDefinitions[n]
          const shortcuts = def.short ? `\n* Shortcut: \`-${def.short}\`` : ''
          const defAliases = def.alias || []
          const aliasText = defAliases.length > 0
            ? `\n* Aliases: ${defAliases.map(a => `\`--${a}\``).join(', ')}`
            : ''
          parts.push(`${def.describe()}${shortcuts}${aliasText}`, '')
        })
      }

      // Add global config section if any exist
      if (globalConfigParams.length > 0) {
        if (commandSpecificParams.length === 0) {
          parts.push('#### Configuration', '')
        }
        globalConfigParams.forEach((n) => {
          const def = subDefinitions[n] || definitions[n]
          const shortcuts = def.short ? `\n* Shortcut: \`-${def.short}\`` : ''
          const defAliases = def.alias || []
          const aliasText = defAliases.length > 0
            ? `\n* Aliases: ${defAliases.map(a => `\`--${a}\``).join(', ')}`
            : ''
          parts.push(`${def.describe()}${shortcuts}${aliasText}`, '')
        })
      }

      return parts.join('\n')
    })

    return src.replace(replacer, subcommandSections.join('\n'))
  }

  // Original behavior for commands without subcommands but with params
  /* istanbul ignore if - all commands with no subcommands have params */
  if (!params) {
    return src
  }

  // Separate command-specific and global config params
  const commandSpecificParams = []
  const globalConfigParams = []

  for (const paramName of params) {
    const isCommandSpecific = commandDefinitions[paramName] && !definitions[paramName]
    /* istanbul ignore if - no current non-subcommand commands have command-specific definitions */
    if (isCommandSpecific) {
      commandSpecificParams.push(paramName)
    } else {
      globalConfigParams.push(paramName)
    }
  }

  const sections = []

  // Add command-specific flags section if any exist
  /* istanbul ignore if - no current non-subcommand commands have command-specific definitions */
  if (commandSpecificParams.length > 0) {
    const commandSpecificConfig = commandSpecificParams.map((n) => {
      const def = commandDefinitions[n]
      const shortcuts = def.short ? `\n* Shortcut: \`-${def.short}\`` : ''
      const defAliases = def.alias || []
      const aliasText = defAliases.length > 0
        ? `\n* Aliases: ${defAliases.map(a => `\`--${a}\``).join(', ')}`
        : ''
      return `${def.describe()}${shortcuts}${aliasText}`
    })

    sections.push(
      '#### Command-Specific Flags',
      '',
      'These flags are specific to this command and are not part of npm\'s global configuration or `.npmrc` files.',
      '',
      commandSpecificConfig.join('\n\n')
    )
  }

  // Add global config section if any exist
  if (globalConfigParams.length > 0) {
    const globalConfig = globalConfigParams.map((n) => {
      const def = commandDefinitions[n] || definitions[n]
      const shortcuts = def.short ? `\n* Shortcut: \`-${def.short}\`` : ''
      return `${def.describe()}${shortcuts}`
    })

    /* istanbul ignore if - no current non-subcommand commands have command-specific definitions */
    if (commandSpecificParams.length > 0) {
      sections.push('', '#### Configuration', '')
    }
    sections.push(globalConfig.join('\n\n'))
  }

  return src.replace(replacer, sections.join('\n'))
}

const replaceConfig = (src, { path }) => {
  const replacer = assertPlaceholder(src, path, TAGS.CONFIG)

  // sort not-deprecated ones to the top
  /* istanbul ignore next - typically already sorted in the definitions file,
   * but this is here so that our help doc will stay consistent if we decide
   * to move them around. */
  const sort = ([keya, { deprecated: depa }], [keyb, { deprecated: depb }]) => {
    return depa && !depb ? 1
      : !depa && depb ? -1
      : localeCompare(keya, keyb)
  }

  const allConfig = Object.entries(definitions).sort(sort)
    .map(([, def]) => def.describe())
    .join('\n\n')

  return src.replace(replacer, allConfig)
}

const replaceShorthands = (src, { path }) => {
  const replacer = assertPlaceholder(src, path, TAGS.SHORTHANDS)

  const sh = Object.entries(shorthands)
    .sort(([shorta, expansiona], [shortb, expansionb]) =>
      // sort by what they're short FOR
      localeCompare(expansiona.join(' '), expansionb.join(' ')) || localeCompare(shorta, shortb)
    )
    .map(([short, expansion]) => {
      // XXX: this is incorrect. we have multicharacter flags like `-iwr` that
      // can only be set with a single dash
      const dash = short.length === 1 ? '-' : '--'
      return `* \`${dash}${short}\`: \`${expansion.join(' ')}\``
    })

  return src.replace(replacer, sh.join('\n'))
}

const replaceHelpLinks = (src) => {
  // replaces markdown links with equivalent-ish npm help commands
  return src.replace(
    /\[`?([\w\s-]+)`?\]\(\/(?:commands|configuring-npm|using-npm)\/(?:[\w\s-]+)\)/g,
    (_, p1) => {
      const term = p1.replace(/npm\s/g, '').replace(/\s+/g, ' ').trim()
      const help = `npm help ${term.includes(' ') ? `"${term}"` : term}`
      return help
    }
  )
}

const transformMan = (src, { data, unified, remarkParse, remarkMan }) => unified()
  .use(remarkParse)
  .use(remarkMan, { version: `NPM@${version}` })
  .processSync(`# ${data.title}(${data.section}) - ${data.description}\n\n${src}`)
  .toString()

const manPath = (name, { data }) => join(`man${data.section}`, `${name}.${data.section}`)

const transformMd = (src, { frontmatter }) => ['---', frontmatter, '---', '', src].join('\n')

module.exports = {
  DOC_EXT,
  TAGS,
  paths: {
    content: resolve(__dirname, 'content'),
    nav: resolve(__dirname, 'content', 'nav.yml'),
    template: resolve(__dirname, 'template.html'),
    man: resolve(__dirname, '..', '..', 'man'),
    html: resolve(__dirname, '..', 'output'),
    md: resolve(__dirname, '..', 'content'),
  },
  usage: replaceUsage,
  params: replaceParams,
  config: replaceConfig,
  shorthands: replaceShorthands,
  version: replaceVersion,
  helpLinks: replaceHelpLinks,
  man: transformMan,
  manPath: manPath,
  md: transformMd,
  html: transformHTML,
  // Testing utilities for command injection
  testing: {
    registerCommand,
    unregisterCommand,
    clearCommandRegistry,
    getCommandByDoc,
  },
}
